/* Что нужно вставить в <head>, чтобы игра стала сборкой под площадку.
 *
 * Знание не про конкретную игру, а про площадки: адрес SDK, имя площадки,
 * порядок скриптов, какие внешние загрузки площадка терпит. Поэтому живёт в
 * game-kit, а не в сборке игры — и переживёт ту сборку, из которой сюда
 * переехало.
 *
 * Обе сборки «Попаданца» берут отсюда: однофайловая (build.mjs) и порт
 * (app/tools/build-app.mjs). Разойтись они не могут — источник один.
 *
 * Чего здесь НЕТ намеренно: списка дополнительных файлов (libs). Он у каждой
 * игры свой — зависит от того, что лежит в её node_modules и в её src, — и
 * тянуть его сюда значит привязать общий модуль к путям одной игры.
 */

/** Метка в шаблоне, вместо которой встаёт голова площадки. Без неё сборка
 *  обязана падать: молча собранная игра без SDK выглядит рабочей и получает
 *  отказ уже на модерации. */
export const HEAD_MARK = '<!--@PLATFORM_HEAD@-->';

export const TARGETS = {
  /* Яндекс Игры: архив должен быть самодостаточным, единственная внешняя
     загрузка — сам SDK площадки, и его подтягивает драйвер в рантайме. */
  yandex: {
    head: [
      `<script>window.__PLATFORM__='yandex';`
        + `window.__SDK_URL='https://yandex.ru/games/sdk/v2';</script>`,
      /* Бутстрап тянет облачные сохранения ДО первого кадра. Позже нельзя: игрок
         на новом устройстве успел бы увидеть пустое прохождение, а поверх него
         через секунду приехало бы настоящее — и что уцелеет, решал бы тот, кто
         записал последним. Он же поднимает SDK, который потом переиспользует
         драйвер рекламы. */
      `<script src="./libs/yandex-boot.js"></script>`,
    ].join('\n'),
    allowCdn: [/yandex\.ru\/games\/sdk/],
  },

  /* VK Games — ВКонтакте и Одноклассники сразу: одно приложение, один VK Bridge.
     Библиотеку кладём внутрь сборки, а не тянем с CDN: игра должна подниматься
     и при недоступном стороннем хостинге. Порядок скриптов важен — мост должен
     существовать до бутстрапа, а бутстрап до игры. */
  vkok: {
    head: [
      `<script src="./libs/vk-bridge.min.js"></script>`,
      `<script>window.__PLATFORM__='vkok';</script>`,
      `<script src="./libs/vkok-boot.js"></script>`,
    ].join('\n'),
    allowCdn: [],
  },

  /* RuStore: те же файлы уезжают в APK, в assets/game/. Сети может не быть
     вовсе, поэтому внешних загрузок здесь не должно остаться ни одной. */
  android: {
    head: `<script>window.__PLATFORM__='android';</script>`,
    allowCdn: [],
  },

  /* CrazyGames — англоязычная витрина. Сам SDK лежит на их CDN и приезжает в
     рантайме: сначала его тянет бутстрап (ему нужны сохранения до первого
     кадра), а драйвер рекламы потом переиспользует уже поднятый экземпляр. */
  crazy: {
    head: [
      `<script>window.__PLATFORM__='crazy';`
        + `window.__SDK_URL='https://sdk.crazygames.com/crazygames-sdk-v3.js';</script>`,
      /* Бутстрап тянет облачные сохранения ДО первого кадра. Позже нельзя: игра
         во фрейме площадки видит localStorage браузера, а не игрока, и на
         телефоне прохождение оказалось бы пустым — а через секунду поверх него
         приехало бы настоящее. */
      `<script src="./libs/crazy-boot.js"></script>`,
    ].join('\n'),
    allowCdn: [/sdk\.crazygames\.com/],
  },

  /* GameDistribution — второй англоязычный канал. Их SDK требует, чтобы
     window.GD_OPTIONS с gameId существовал ДО загрузки скрипта, поэтому объект
     объявляется здесь, а сам скрипт подтягивает драйвер. gameId выдаётся в
     кабинете при заведении игры; до этого он пустой, и драйвер просто не
     показывает рекламу — игра работает как без площадки. */
  gamedist: {
    head: `<script>window.__PLATFORM__='gamedist';`
      + `window.GD_OPTIONS={gameId:'@GD_ID@',onEvent:function(){}};`
      + `window.__SDK_URL='https://html5.api.gamedistribution.com/main.min.js';</script>`,
    allowCdn: [/html5\.api\.gamedistribution\.com/, /gamedistribution\.com/],
  },
};

/** Адреса, которые адресами загрузки не являются.
 *
 *  Проверка готового файла ищет любые http(s)-адреса и валит сборку, если нашла
 *  посторонний. Это правильно: у Яндекса внешние загрузки против правил, а в APK
 *  сети может не быть вовсе. Но вместе с three в бандл приезжают строки из её
 *  собственных исходников — пространства имён и ссылки на статьи в комментариях
 *  внутри GLSL (комментарий внутри шейдера — это содержимое строки, и
 *  минификатор его не трогает).
 *
 *  Список ПЕРЕЧИСЛЯЕТ известное, а не смягчает проверку шаблоном: любой новый
 *  адрес по-прежнему валит сборку, и это то, чего мы хотим. */
export const INERT_URLS = [
  /(^|\/\/|\.)w3\.org\//,      // пространства имён XML и SVG для createElementNS
  /(^|\/\/|\.)jcgt\.org\//,    // ссылка на статью в комментарии GLSL-шейдера three
  /(^|\/\/|\.)threejs\.org\//, // ссылки из текстов console.warn самой three
  /(^|\/\/|\.)brm\.io\//,      // домашняя страница matter-js из её же заголовка
  /(^|\/\/)vk\.com\/app(?:["'`]|\?)/, // маршрут VK Bridge для ссылки/шаринга, не загрузка ресурса
];

/**
 * Проверить ГОТОВЫЙ файл, а не намерение.
 *
 * Любой недосмотр в подстановке виден здесь и нигде больше: собранная игра — это
 * то, что уедет на площадку, и смотреть надо на неё.
 *
 * @returns {string[]} список проблем; пустой — можно подавать
 */
export function auditBuild(html, target, files = [], code = '') {
  const t = TARGETS[target];
  const problems = [];
  if (!t) return ['неизвестная площадка: ' + target];

  /* Смотрим и на разметку, и на СОБРАННЫЙ КОД. Проверять только index.html —
     значит проверять обёртку: у игры со сборщиком весь её код лежит в отдельном
     файле бандла, и посторонняя загрузка окажется именно там. Это не гипотеза:
     первая же игра, собранная через vite, привезла в бандле http-адрес из
     заголовка своей физической библиотеки, а проверка отчиталась «чисто». */
  const urls = [...([html, code].join('\n')).matchAll(/https?:\/\/[^"'\s)]+/g)].map((m) => m[0])
    .filter((u) => !INERT_URLS.some((re) => re.test(u)));
  const foreign = [...new Set(urls.filter((u) => !t.allowCdn.some((re) => re.test(u))))];
  if (foreign.length) problems.push('посторонние загрузки: ' + foreign.slice(0, 5).join(', '));

  const insecure = [...new Set(urls.filter((u) => /^http:\/\//.test(u)))];
  if (insecure.length) problems.push('незащищённый http: ' + insecure.slice(0, 3).join(', '));

  if (!new RegExp(`__PLATFORM__\\s*=\\s*'${target}'`).test(html)) {
    problems.push(`не подставилось window.__PLATFORM__='${target}'`);
  }

  /* Имена файлов в архиве. Пробел или кириллица ломают распаковку у части
     площадок, и узнаётся это уже отказом. */
  const bad = files.filter((f) => /[^\x20-\x7E]/.test(f) || /\s/.test(f) || f.includes('\\'));
  if (bad.length) problems.push('плохие имена файлов: ' + bad.slice(0, 3).join(', '));

  return problems;
}
