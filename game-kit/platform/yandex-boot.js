/* Бутстрап Яндекс Игр: облачные сохранения до первого кадра.
 *
 * Зачем отдельным скриптом в <head>, а не внутри драйвера рекламы. Прогресс надо
 * забрать из облака ДО того, как игра прочитает localStorage. Драйвер поднимает
 * SDK позже, по ходу игры, — к этому моменту титул уже отрисован, и игрок на
 * новом устройстве успел увидеть пустое прохождение. Через секунду поверх него
 * приехало бы настоящее, и что уцелеет, решал бы тот, кто записал последним.
 *
 * Игра ждёт window.__PLATFORM_READY. Промис ОБЯЗАН разрешиться в любом случае:
 * нет сети, нет SDK, площадка молчит — играем на локальном хранилище. Игра,
 * которая не начинается из-за облака, хуже игры без облака.
 *
 * МЕТКИ ВРЕМЕНИ обязательны. Без них переезд между устройствами затирает
 * прогресс: локальное пустое перезапишет облачное полное или наоборот. Рядом с
 * каждым ключом лежит его метка, и берётся та версия, что свежее.
 *
 * ОБЛАСТЬ СОХРАНЕНИЙ здесь не нужна, в отличие от ВК: у Яндекса игра открывается
 * со своего адреса, и localStorage у неё свой. Поэтому ключи локально не
 * скоупятся — но код всё равно ходит через scoped(), чтобы вести себя одинаково,
 * если область когда-нибудь появится.
 *
 * ЧТО КЛАСТЬ В ОБЛАКО, решает игра: window.__CLOUD_KEYS объявляет сборка ДО
 * этого скрипта. Не объявила — облака не будет, и это честнее, чем угадывать.
 */
(function () {
  var CLOUD_KEYS = (window.__CLOUD_KEYS || []).slice(0, 8);
  /* Ключи-МНОЖЕСТВА: для них «кто свежее, тот и прав» — неправильное правило.
     Коллекция открытых финалов на двух устройствах иначе затирает сама себя:
     три финала с телефона против двух других с компьютера — и чьи-то теряются,
     хотя игрок честно открыл все пять. Для множеств правильное правило —
     объединение, и свежесть тут ни при чём. */
  var MERGE_KEYS = (window.__MERGE_KEYS || []);
  function unionInto(key, cloudRaw, stamp) {
    var loc = [], rem = [];
    try { loc = JSON.parse(localStorage.getItem(scoped(key))) || []; } catch (e) {}
    try { rem = JSON.parse(cloudRaw) || []; } catch (e) {}
    if (!Array.isArray(loc)) loc = []; if (!Array.isArray(rem)) rem = [];
    var seen = {}, out = [];
    loc.concat(rem).forEach(function (x) {
      var k = typeof x === 'string' ? x : JSON.stringify(x);
      if (!seen[k]) { seen[k] = 1; out.push(x); }
    });
    try {
      localStorage.setItem(scoped(key), JSON.stringify(out));
      setLocalStamp(key, Math.max(stamp || 0, localStamp(key)));
    } catch (e) {}
  }
  if (!CLOUD_KEYS.length) {
    console.warn('[Яндекс] не объявлен window.__CLOUD_KEYS — облачных сохранений не будет');
  }

  var BOOT_TIMEOUT = 2500;     // столько ждём облако, дальше играем на localStorage
  var PUSH_DEBOUNCE = 1500;    // сейв дёргается часто, а частые записи площадка не любит
  var RETRY_DELAY = 6000;      // одна повторная попытка прочитать облако, если первая не удалась

  var scoped = function (key) { return key + (window.__SAVE_SCOPE || ''); };
  function stampKey(key) { return scoped(key) + '__t'; }
  function localStamp(key) {
    var v = 0;
    try { v = parseInt(localStorage.getItem(stampKey(key)), 10) || 0; } catch (e) {}
    return v;
  }
  function setLocalStamp(key, t) {
    try { localStorage.setItem(stampKey(key), String(t)); } catch (e) {}
  }

  var player = null;           // объект игрока Яндекса
  var ready = false;           // облако ответило и его можно использовать на запись

  /* ---- запись в облако ---- */
  var timers = {};
  /* Ключи, записанные локально ПОКА ОБЛАКО ЕХАЛО. Метки у них уже стоят, а в
     облако они не уехали — отправлять было некуда. Догоняем сразу, как облако
     ответит: иначе партия, начатая в окне ожидания, останется только на этом
     устройстве, а на соседнем игрок увидит вчерашнее прохождение. */
  var pending = {};
  window.__cloudPut = function (key, value) {
    /* Чужой ключ — ни метки, ни отправки: метка нужна ровно тем ключам, у
       которых есть облачный двойник, чтобы было с чем её сравнивать. */
    if (CLOUD_KEYS.indexOf(key) < 0) return;
    /* Значение не передали — читаем сами. Забытый второй аргумент уехал бы в
       облако конвертом без поля v, а гидратация трактует отсутствующее v как
       «ключ удалён»: на другом устройстве прохождение просто исчезло бы. Явный
       null оставляем как есть — это и означает удаление. */
    if (value === undefined) { try { value = localStorage.getItem(scoped(key)); } catch (e) { value = null; } }
    var now = Date.now();
    /* МЕТКА СТАВИТСЯ ВСЕГДА — до всех проверок готовности облака.
       Задний рубеж бутстрапа 2.5 с, а облако отвечает когда ответит: замеряли
       двенадцатую секунду у Яндекса и двадцать пятую на мобильном интернете ВК.
       Всё, что игрок успевал записать в это окно, ложилось БЕЗ метки: localStamp
       равнялся нулю, гидратация объявляла часовой давности облако более свежим —
       и живая партия затиралась. Готовность облака решает, отправлять ли, и
       только это; на локальную запись она влиять не должна. */
    setLocalStamp(key, now);
    if (!ready || !player) { pending[key] = now; return; }
    clearTimeout(timers[key]);
    timers[key] = setTimeout(function () {
      var patch = {};
      patch[key] = { t: now, v: value };
      /* flush:false — площадка сама решит, когда отправить. Так частые сейвы не
         превращаются в частые запросы. */
      try { player.setData(patch, false).catch(function () {}); } catch (e) {}
    }, PUSH_DEBOUNCE);
  };

  /* Догнать облако тем, что игрок записал, пока оно ехало. Зовётся один раз, в
     момент готовности облака, и укладывается в бюджет вызовов: ключей самое
     большее восемь, а дебаунс склеит их с обычными сейвами. */
  function flushPending() {
    var keys = Object.keys(pending);
    for (var i = 0; i < keys.length; i++) {
      var key = keys[i], t = pending[key];
      delete pending[key];
      /* Метка успела смениться — значит поверх нашей записи уже легло другое.
         Либо гидратация подняла более свежее облачное (тогда в облаке оно и
         так есть), либо игрок записал ещё раз (эта запись уедет своим
         порядком). Отправлять устаревшее значение нельзя: мы вернули бы в
         облако то, от чего игрок уже ушёл.
         Множества — исключение: объединённый список надо вернуть в облако в
         любом случае, иначе второе устройство не узнает про наши финалы. */
      if (localStamp(key) !== t && MERGE_KEYS.indexOf(key) < 0) continue;
      /* Значение перечитываем из хранилища: у множества там уже ОБЪЕДИНЁННЫЙ
         список, а не то, что игрок записал до приезда облака. */
      window.__cloudPut(key);
    }
  }

  /* ---- чтение из облака при старте ---- */
  function hydrate() {
    return player.getData(CLOUD_KEYS).then(function (data) {
      data = data || {};
      for (var i = 0; i < CLOUD_KEYS.length; i++) {
        var key = CLOUD_KEYS[i];
        var env = data[key];
        if (!env || typeof env.t !== 'number') continue;
        /* Множества объединяются ВСЕГДА, независимо от свежести: у них обе
           стороны правы. Сравнение меток — только для одиночных значений. */
        if (MERGE_KEYS.indexOf(key) >= 0) { unionInto(key, env.v, env.t); continue; }
        if (env.t <= localStamp(key)) continue;          // локальная версия свежее — не трогаем
        try {
          if (env.v === null || env.v === undefined) localStorage.removeItem(scoped(key));
          else localStorage.setItem(scoped(key), env.v);
          setLocalStamp(key, env.t);
        } catch (e) {}
      }
      ready = true;
      /* Порядок важен: сперва догоняем облако тем, что игрок записал в окно
         ожидания (гидратация выше уже решила, чья версия свежее), и только
         потом сообщаем игре о приезде. */
      flushPending();
      /* Облако могло приехать позже заднего рубежа: игра к этому моменту уже решила
         судьбу кнопки «Продолжить» — и решила по пустому localStorage. */
      try { window.__cloudArrived && window.__cloudArrived(); } catch (e) {}
    });
  }

  window.__PLATFORM_READY = new Promise(function (resolve) {
    var done = false;
    var finish = function () { if (!done) { done = true; resolve(); } };
    /* Задний рубеж стоит ПЕРВЫМ: что бы дальше ни случилось — не поднялся SDK,
       не ответило облако, упал разбор — игра начнётся. */
    setTimeout(finish, BOOT_TIMEOUT);

    /* Вне площадки SDK не грузим — то же правило, что у драйвера рекламы, и по
       той же причине: локальный файл, localhost и GitHub Pages открывают ту же
       сборку в автотестах и как демо, а вне фрейма площадки её SDK сыплет
       необработанными отказами промисов («No parent to post message») в консоль
       каждому, кто её открыл. Флаг сборки говорит, ЧЕЙ SDK подключать, а не то,
       что мы уже на площадке. */
    var off = location.protocol === 'file:' || !location.hostname ||
      /^(localhost|127\.0\.0\.1|\[::1\])$/i.test(location.hostname) ||
      /(^|\.)github\.io$/i.test(location.hostname);
    var src = window.__SDK_URL;
    if (off || !src || !CLOUD_KEYS.length) { finish(); return; }

    var s = document.createElement('script');
    s.src = src;
    s.onerror = finish;
    s.onload = function () {
      try {
        /* Промис SDK кладём наружу: драйвер рекламы возьмёт готовый вместо того,
           чтобы поднимать его вторым разом. */
        var p = window.YaGames.init();
        window.__YA_SDK = p;
        p.then(function (ysdk) {
          /* scopes:false — не спрашиваем у игрока разрешения на личные данные:
             для сохранений оно не нужно, а окно запроса на старте отпугивает.
             Неавторизованный игрок тоже получает player — его данные площадка
             хранит на устройстве, и наш код об этом знать не обязан. */
          return ysdk.getPlayer({ scopes: false });
        }).then(function (pl) {
          player = pl;
          /* Одна сетевая икота на старте не должна отключать облако на всю сессию.
             Раньше ready поднимался ТОЛЬКО внутри удачного hydrate, а __cloudPut
             первой строкой смотрит на ready — то есть после любого отказа getData
             весь дальнейший прогресс за сеанс не уезжал в облако вообще. Локально
             всё цело, поэтому игрок не замечал ничего до пересадки на другое
             устройство, где обнаруживал старое прохождение.
             Пробуем прочитать ещё раз, и только если и вторая попытка не удалась —
             разрешаем запись вслепую: сессия без облачных сохранений хуже, чем
             сессия, начатая с локального состояния. */
          return hydrate().catch(function () {
            return new Promise(function (res) { setTimeout(res, RETRY_DELAY); })
              .then(hydrate)
              /* Записываем вслепую — и первым делом отдаём в облако то, что
                 накопилось за обе неудачные попытки: локальные метки у этих
                 ключей уже стоят, терять их отправку незачем. */
              .catch(function () { ready = true; flushPending(); });
          });
        }).then(finish, finish);
      } catch (e) { finish(); }
    };
    document.head.appendChild(s);
  });
})();
