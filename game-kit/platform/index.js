/**
 * Определить площадку.
 *
 * Значение подставляет СБОРКА через window.__PLATFORM__ — угадывать в рантайме
 * нельзя, потому что SDK у каждой площадки свой и подключается ещё в <head>,
 * до того как этот код исполнится.
 */
export function detectPlatform() {
  if (typeof window.__PLATFORM__ === 'string' && window.__PLATFORM__) return window.__PLATFORM__;
  if (location.protocol === 'file:') return 'none';
  const h = location.hostname;
  if (!h || /^(localhost|127\.0\.0\.1|\[::1\])$/i.test(h)) return 'none';
  return 'none';
}

/**
 * Мы вне площадки, даже если сборка платформенная.
 *
 * Флаг сборки говорит, ЧЕЙ SDK подключать, а не то, что мы уже на площадке:
 * ту же dist/yandex открывают и локально в автотестах, и на GitHub Pages как
 * демонстрацию. Грузить там SDK нельзя — вне её фрейма он сыплет
 * необработанными отказами промисов, и это видит любой, кто откроет консоль.
 *
 * Проверка нужна только драйверам, которые тянут скрипт со стороны. Драйвер,
 * чья библиотека лежит внутри сборки, свои отказы обрабатывает сам, и эта
 * проверка его касаться не должна — иначе сломается собственный хостинг,
 * если он окажется на тех же Pages.
 */
export function offPlatform() {
  return location.protocol === 'file:' ||
    !location.hostname ||
    /^(localhost|127\.0\.0\.1|\[::1\])$/i.test(location.hostname) ||
    /(^|\.)github\.io$/i.test(location.hostname);
}

