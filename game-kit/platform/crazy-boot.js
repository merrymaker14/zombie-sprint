/* Бутстрап CrazyGames: облачные сохранения до первого кадра.
 *
 * Зачем отдельным скриптом в <head>, а не внутри драйвера рекламы — причина та
 * же, что у Яндекса и ВК: прогресс надо забрать из облака ДО того, как игра
 * прочитает localStorage. Драйвер поднимает SDK позже, по ходу игры, — к этому
 * моменту титул уже отрисован, и игрок на новом устройстве успел увидеть пустое
 * прохождение. Через секунду поверх него приехало бы настоящее, и что уцелеет,
 * решал бы тот, кто записал последним.
 *
 * Почему облако нужно именно здесь. Игра на CrazyGames открывается во фрейме их
 * домена, и localStorage там привязан к браузеру, а не к игроку, — на телефоне
 * прохождения нет. Аккаунт у площадки при этом есть, и документация модуля data
 * требует прямо: «You need to fully rely on the Data Module save (for both guest
 * and logged-in users on CrazyGames) and avoid relying on local saves».
 *
 * Чем модуль данных CrazyGames отличается от соседей:
 *   • он СИНХРОННЫЙ и повторяет интерфейс localStorage: getItem / setItem /
 *     removeItem / clear. Асинхронна здесь только инициализация — SDK
 *     предзагружает все данные игрока в момент init(), и до его ответа читать
 *     нечего.
 *   • лимит — 1 МБ на игрока НА ВСЮ ИГРУ, а не на ключ. Профили героев с их
 *     PNG-аватарами не помещаются в такой бюджет вдвоём с сейвом, поэтому в
 *     облако не едут: они объявлены в __LOCAL_KEYS и остаются локальными.
 *   • вне домена площадки SDK переходит в состояние disabled, и обращение к
 *     любому его модулю БРОСАЕТ исключение. Это не поломка, а штатный режим
 *     локального файла и чужого хостинга: там мы просто играем на localStorage.
 *   • модуль включается тумблером «Progress Save» («Does your game save
 *     progress?») в форме подачи игры. Не включён — data отвечает ошибкой
 *     dataModuleDisabled, и облака не будет, сколько его ни зови.
 *
 * Игра ждёт window.__PLATFORM_READY. Промис ОБЯЗАН разрешиться в любом случае:
 * нет сети, нет SDK, площадка молчит — играем на локальном хранилище. Игра,
 * которая не начинается из-за облака, хуже игры без облака.
 *
 * МЕТКИ ВРЕМЕНИ обязательны, как и у соседей. Без них переезд между
 * устройствами затирает прогресс: локальное пустое перезапишет облачное полное
 * или наоборот. Рядом с каждым ключом лежит его метка, и берётся та версия, что
 * свежее.
 *
 * ОБЛАСТЬ СОХРАНЕНИЙ здесь не нужна, как и у Яндекса: игрок у площадки один и
 * записи разложены по аккаунтам ею самой. Но код всё равно ходит через
 * scoped(), чтобы вести себя одинаково, если область когда-нибудь появится.
 *
 * ЧТО КЛАСТЬ В ОБЛАКО, решает игра: window.__CLOUD_KEYS объявляет сборка ДО
 * этого скрипта. Не объявила — облака не будет, и это честнее, чем угадывать.
 */
(function () {
  'use strict';

  var CLOUD_KEYS = (window.__CLOUD_KEYS || []).slice(0, 8);
  /* Ключи-МНОЖЕСТВА: для них «кто свежее, тот и прав» — неправильное правило.
     Коллекция открытых финалов на двух устройствах иначе затирает сама себя:
     три финала с телефона против двух других с компьютера — и чьи-то теряются,
     хотя игрок честно открыл все пять. Для множеств правильное правило —
     объединение, и свежесть тут ни при чём. */
  var MERGE_KEYS = (window.__MERGE_KEYS || []);
  function unionInto(key, cloudRaw, stamp) {
    var loc = [], rem = [];
    try { loc = JSON.parse(localStorage.getItem(scoped(key))) || []; } catch (e) {}
    try { rem = JSON.parse(cloudRaw) || []; } catch (e) {}
    if (!Array.isArray(loc)) loc = []; if (!Array.isArray(rem)) rem = [];
    var seen = {}, out = [];
    loc.concat(rem).forEach(function (x) {
      var k = typeof x === 'string' ? x : JSON.stringify(x);
      if (!seen[k]) { seen[k] = 1; out.push(x); }
    });
    try {
      localStorage.setItem(scoped(key), JSON.stringify(out));
      setLocalStamp(key, Math.max(stamp || 0, localStamp(key)));
    } catch (e) {}
  }
  if (!CLOUD_KEYS.length) {
    console.warn('[CrazyGames] не объявлен window.__CLOUD_KEYS — облачных сохранений не будет');
  }

  var BOOT_TIMEOUT = 2500;     // столько ждём облако, дальше играем на localStorage
  var PUSH_DEBOUNCE = 1500;    // сейв дёргается часто, а SDK и сам копит записи около секунды
  /* Потолок на один ключ. Площадка меряет лимит НЕ по ключу, а по игроку целиком:
     1 МБ на всё. Ключей самое большее восемь (см. срез выше), поэтому 120 000
     символов на каждый — это ровно тот потолок, при котором даже полный набор
     ключей не выходит за мегабайт. Переросший ключ не режем и не роняем: он
     остаётся жить в localStorage, а в консоли появляется причина. */
  var MAX_VALUE = 120000;

  var scoped = function (key) { return key + (window.__SAVE_SCOPE || ''); };
  function stampKey(key) { return scoped(key) + '__t'; }
  function localStamp(key) {
    var v = 0;
    try { v = parseInt(localStorage.getItem(stampKey(key)), 10) || 0; } catch (e) {}
    return v;
  }
  function setLocalStamp(key, t) {
    try { localStorage.setItem(stampKey(key), String(t)); } catch (e) {}
  }

  var ready = false;           // облако ответило и его можно использовать на запись
  var warned = {};

  /* Модуль данных берём каждый раз заново, а не запоминаем ссылку: до init() он
     бросает «CrazySDK is not initialized yet», а после — живёт столько же,
     сколько SDK. Запомненная ссылка тут ничего не экономит и только создаёт
     шанс подержаться за отвалившийся объект. */
  function dataModule() { return window.CrazyGames.SDK.data; }

  /* ---- запись в облако ---- */
  var timers = {};
  /* Ключи, записанные локально ПОКА ОБЛАКО ЕХАЛО. Метки у них уже стоят, а в
     облако они не уехали — отправлять было некуда. Догоняем сразу, как облако
     ответит. Здесь окно ожидания шире, чем у соседей: init() ждёт ещё и загрузку
     их рекламного скрипта, а он приезжает не мгновенно. */
  var pending = {};
  window.__cloudPut = function (key, value) {
    /* Чужой ключ — ни метки, ни отправки: метка нужна ровно тем ключам, у
       которых есть облачный двойник, чтобы было с чем её сравнивать. Профили
       героев сюда не попадают намеренно — они в __LOCAL_KEYS. */
    if (CLOUD_KEYS.indexOf(key) < 0) return;
    /* Значение не передали — читаем сами. Забытый второй аргумент уехал бы в
       облако конвертом без поля v, а гидратация трактует отсутствующее v как
       «ключ удалён»: на другом устройстве прохождение просто исчезло бы. Явный
       null оставляем как есть — это и означает удаление. */
    if (value === undefined) { try { value = localStorage.getItem(scoped(key)); } catch (e) { value = null; } }
    var now = Date.now();
    /* МЕТКА СТАВИТСЯ ВСЕГДА — до всех проверок готовности облака.
       Задний рубеж бутстрапа 2.5 с, а init() отвечает когда ответит. Всё, что
       игрок успевал записать в это окно, ложилось БЕЗ метки: localStamp
       равнялся нулю, гидратация объявляла вчерашнее облако более свежим — и
       живая партия затиралась. Готовность облака решает, отправлять ли, и
       только это; на локальную запись она влиять не должна. И тем более здесь,
       где облака может не быть вовсе (чужой домен, выключенный тумблер
       «Progress Save»): метка нужна и в этом случае — иначе следующий запуск
       сочтёт запись «без времени». */
    setLocalStamp(key, now);
    if (!ready) { pending[key] = now; return; }
    clearTimeout(timers[key]);
    timers[key] = setTimeout(function () {
      var body = JSON.stringify({ t: now, v: value });
      if (body.length > MAX_VALUE) {
        if (!warned[key]) { warned[key] = 1;
          console.warn('[облако] ' + key + ' не помещается в бюджет CrazyGames (' +
            body.length + ' символов) — этот ключ остаётся только в localStorage'); }
        return;
      }
      /* В облако ключ уходит БЕЗ области: там записи и так разложены по игрокам
         самой площадкой. Область появляется только на локальной стороне. */
      try { dataModule().setItem(key, body); } catch (e) {}
    }, PUSH_DEBOUNCE);
  };

  /* Догнать облако тем, что игрок записал, пока оно ехало. Зовётся в момент
     готовности облака — то есть после удачной гидратации; если модуль данных
     недоступен, ready не поднимается, и отправлять всё равно некуда. Бюджет не
     страдает: ключей самое большее восемь, а дебаунс склеит их с обычными
     сейвами. */
  function flushPending() {
    var keys = Object.keys(pending);
    for (var i = 0; i < keys.length; i++) {
      var key = keys[i], t = pending[key];
      delete pending[key];
      /* Метка успела смениться — значит поверх нашей записи уже легло другое.
         Либо гидратация подняла более свежее облачное (тогда в облаке оно и
         так есть), либо игрок записал ещё раз (эта запись уедет своим
         порядком). Отправлять устаревшее значение нельзя: мы вернули бы в
         облако то, от чего игрок уже ушёл.
         Множества — исключение: объединённый список надо вернуть в облако в
         любом случае, иначе второе устройство не узнает про наши финалы. */
      if (localStamp(key) !== t && MERGE_KEYS.indexOf(key) < 0) continue;
      /* Значение перечитываем из хранилища: у множества там уже ОБЪЕДИНЁННЫЙ
         список, а не то, что игрок записал до приезда облака. */
      window.__cloudPut(key);
    }
  }

  /* ---- чтение из облака ---- */
  function hydrate() {
    /* Сначала ЧИТАЕМ ВСЁ, и только потом раскладываем. Порядок не косметический:
       вне домена площадки первый же getItem бросает GeneralError('sdkDisabled'),
       и при чтении вперемешку с записью мы успели бы наполовину переписать
       localStorage тем, что прочли до отказа. Так отказ застаёт нас до того, как
       мы что-то тронули. */
    var mod = dataModule(), raws = [], i;
    for (i = 0; i < CLOUD_KEYS.length; i++) raws.push(mod.getItem(CLOUD_KEYS[i]));

    for (i = 0; i < CLOUD_KEYS.length; i++) {
      var key = CLOUD_KEYS[i], raw = raws[i];
      if (raw === null || raw === undefined || raw === '') continue;
      var env;
      try { env = JSON.parse(raw); } catch (e) { continue; }
      if (!env || typeof env.t !== 'number') continue;
      /* Множества объединяются ВСЕГДА, независимо от свежести: у них обе
         стороны правы. Сравнение меток — только для одиночных значений. */
      if (MERGE_KEYS.indexOf(key) >= 0) { unionInto(key, env.v, env.t); continue; }
      if (env.t <= localStamp(key)) continue;          // локальная версия свежее — не трогаем
      try {
        if (env.v === null || env.v === undefined) localStorage.removeItem(scoped(key));
        else localStorage.setItem(scoped(key), env.v);
        setLocalStamp(key, env.t);
      } catch (e) {}
    }
    ready = true;
    /* Порядок важен: сперва догоняем облако тем, что игрок записал в окно
       ожидания (разбор выше уже решил, чья версия свежее), и только потом
       сообщаем игре о приезде. */
    flushPending();
    /* Облако могло приехать позже заднего рубежа: игра к этому моменту уже решила
       судьбу кнопки «Продолжить» — и решила по пустому localStorage. Здесь это
       случается чаще, чем у соседей: init() у CrazyGames ждёт ещё и загрузку их
       рекламного скрипта, а он приезжает не мгновенно. */
    try { window.__cloudArrived && window.__cloudArrived(); } catch (e) {}
  }

  /* Игрок может войти в аккаунт ПРЯМО ПО ХОДУ игры — площадка показывает своё
     окно входа сама, без нашего участия. В этот момент модуль данных под нами
     подменяется: гостевые записи либо переезжают в аккаунт, либо уступают место
     тому, что в аккаунте уже лежало (и наоборот при выходе). Значит, надо
     перечитать — иначе игрок войдёт под своим именем и не увидит прохождения,
     ради которого входил. Затирания тут бояться нечего: правила те же, что при
     старте, — метки времени для одиночных ключей, объединение для множеств. */
  function watchAuth() {
    try {
      var user = window.CrazyGames.SDK.user;
      if (user && user.addAuthListener) {
        user.addAuthListener(function () { try { hydrate(); } catch (e) {} });
      }
    } catch (e) {}
  }

  /* Второй раз тот же SDK поднимать нечем и незачем.
     Драйвер рекламы (game-kit/platform/drivers.js) грузит crazygames-sdk-v3.js
     сам — он умеет работать и без бутстрапа. Но их скрипт последней строкой
     делает безусловное window.CrazyGames = { SDK: новый экземпляр }: вторая
     загрузка выбросила бы уже проинициализированный SDK, начала бы второе
     рукопожатие с площадкой и вторую загрузку рекламного скрипта, а между этими
     двумя мгновениями любой наш setItem падал бы с «not initialized yet».
     Поэтому пришпиливаем ПЕРВЫЙ экземпляр: повторное присваивание молча
     игнорируется, а драйверу достаётся готовый SDK — init() у него кеширует
     свой промис и второй раз ничего не делает. Ровно то же переиспользование,
     которое у Яндекса сделано явно через window.__YA_SDK.
     configurable:true оставлено намеренно: если площадка однажды перейдёт с
     присваивания на defineProperty, наш замок просто уступит место, а не
     уронит их скрипт. */
  function pinSdkInstance() {
    var pinned = window.CrazyGames;
    try {
      Object.defineProperty(window, 'CrazyGames', {
        configurable: true, enumerable: true,
        get: function () { return pinned; },
        set: function (v) { if (!pinned) pinned = v; }
      });
    } catch (e) {}
  }

  window.__PLATFORM_READY = new Promise(function (resolve) {
    var done = false;
    var finish = function () { if (!done) { done = true; resolve(); } };
    /* Задний рубеж стоит ПЕРВЫМ: что бы дальше ни случилось — не поднялся SDK,
       не ответило облако, упал разбор — игра начнётся. */
    setTimeout(finish, BOOT_TIMEOUT);

    /* Вне площадки SDK не грузим — то же правило, что у драйвера рекламы, и по
       той же причине: локальный файл, localhost и GitHub Pages открывают ту же
       сборку в автотестах и как демо, а вне их фрейма SDK уходит в состояние
       disabled и отвечает отказом на всё. Флаг сборки говорит, ЧЕЙ SDK
       подключать, а не то, что мы уже на площадке. */
    var off = location.protocol === 'file:' || !location.hostname ||
      /^(localhost|127\.0\.0\.1|\[::1\])$/i.test(location.hostname) ||
      /(^|\.)github\.io$/i.test(location.hostname);
    var src = window.__SDK_URL;
    if (off || !src || !CLOUD_KEYS.length) { finish(); return; }

    pinSdkInstance();

    var s = document.createElement('script');
    s.src = src;
    s.onerror = finish;
    s.onload = function () {
      try {
        var p = window.CrazyGames.SDK.init();
        /* Промис инициализации кладём наружу — по образцу window.__YA_SDK.
           Драйвер рекламы сегодня его не спрашивает (ему хватает пришпиленного
           экземпляра выше), но когда спросит, готовый ответ уже будет лежать. */
        window.__CRAZY_SDK = p;
        p.then(function () {
          /* Повторной попытки здесь нет намеренно, в отличие от Яндекса. Там
             getData — сетевой запрос, и одна икота не повод отключать облако на
             сеанс. Здесь чтение синхронное и падает оно ровно по одной причине —
             модуль данных недоступен (чужой домен, выключенный тумблер
             «Progress Save»). Такое повтором не лечится: перечитать имеет смысл
             только когда сменился игрок, и это делает watchAuth. */
          try { hydrate(); } catch (e) {}
          watchAuth();
        }).then(finish, finish);
      } catch (e) { finish(); }
    };
    document.head.appendChild(s);
  });
})();
